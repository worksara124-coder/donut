#!/usr/bin/env bash
# Regenerates the scroll-scrub image sequences from the source videos.
# Usage: bash scripts/build-frames.sh   (requires ffmpeg)
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=media-src/videos
OUT=public/frames
# name | source file | first frame | frame count | desktop width | mobile width
# (keep names and counts in sync with lib/timeline.ts)
SCENES=(
  "mood|scene-01-02-mood-flying-donut-1080p.mp4|0|190|1920|1280"
  "zoom|scene-03-cinematic-zoom-720p.mp4|112|128|1280|960"
  "duo|scene-04-donut-duo-720p.mp4|0|192|1280|960"
  "bag|scene-05-packaging-1080p.mp4|0|190|1920|1280"
)
rm -rf "$OUT"
for row in "${SCENES[@]}"; do
  IFS='|' read -r name file start count dw mw <<<"$row"
  mkdir -p "$OUT/$name/d" "$OUT/$name/m"
  sel="select='gte(n\,$start)'"
  ffmpeg -v error -y -i "$SRC/$file" -vf "$sel,scale=$dw:-2:flags=lanczos,unsharp=5:5:0.5:5:5:0.0" -fps_mode passthrough -frames:v "$count" -c:v libwebp -quality 88 -compression_level 5 "$OUT/$name/d/%04d.webp"
  ffmpeg -v error -y -i "$SRC/$file" -vf "$sel,scale=$mw:-2:flags=lanczos,unsharp=5:5:0.5:5:5:0.0" -fps_mode passthrough -frames:v "$count" -c:v libwebp -quality 84 -compression_level 5 "$OUT/$name/m/%04d.webp"
  # poster = first frame
  ffmpeg -v error -y -i "$SRC/$file" -vf "$sel" -frames:v 1 -q:v 2 "$OUT/$name/poster.jpg"
  echo "$name: $(ls "$OUT/$name/d" | wc -l) frames"
done
du -sh "$OUT"/*/d "$OUT"/*/m
# new version stamp: frame URLs change, so no browser shows stale cached frames
cat > lib/framesVersion.ts <<EOF
// Generated by scripts/build-frames.sh — changes every time the frames are regenerated,
// so browsers never reuse old cached frames.
export const FRAMES_VERSION = "$(date +%Y%m%d-%H%M%S)";
EOF
